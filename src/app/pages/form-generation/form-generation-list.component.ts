    private clearSearchFieldValues() {
        for (const field of this.fieldDefinitionsSearch) {
            if (isPassivationSearchField(field)) {
                field.value = true;
                continue;
            }

            field.value = null;
        }
    }

    // ribalta le proprieta dal form di ricerca in alto, sulla fieldDefinitionsSearch
    private preSearch() {
        this.clearSearchFieldValues();
        applySearchFormValues(this.fieldDefinitionsSearch, this.activeSearchValues);
        this.debug('preSearch', {
            activeSearchValues: this.activeSearchValues,
            mappedSearchFields: this.fieldDefinitionsSearch
                .filter(field => field.search_field_name)
                .map(field => ({
                    name: field.name,
                    searchField: field.search_field_name,
                    value: field.value
                }))
                .filter(field => field.value != null && field.value !== '')
        });
        this.persistListState();
    }
