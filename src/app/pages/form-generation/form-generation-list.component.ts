    public loaddata(datatable?: any) {
        this.debug('loaddata:start', {
            tableFirst: this.tableFirst,
            tableRows: this.tableRows,
            apiStart: this.apiService._start,
            apiLimit: this.apiService._limit,
            activeSearchValues: this.activeSearchValues
        });
        this.preLoaddata();
        const tableKeyFieldName = this.getTableKeyFieldName();

        // if (this.searchForm && this.searchForm.value) {
        //     const objToSearch = JSON.parse(JSON.stringify(this.searchForm.value));
        //     for (const k in objToSearch) {
        //         if (objToSearch.hasOwnProperty(k)) {
        //             for (const field of this.fieldDefinitionsSearch) {
        //                 if (field.name === k) {
        //                     field.value = objToSearch[field.name];
        //                 }
        //             }
        //         }
        //     }
        // }
        // valorizza valiri di ricerca con le fileddefinitions
        this.preSearch();

        this.apiService._limit = this.tableRows;
        this.apiService.getList(this.metadataName, this.fieldDefinitionsSearch).subscribe(
            model => {
                this.debug('loaddata:response', {
                    modelLength: model.length,
                    listSize: this.apiService.listSize,
                    tableFirst: this.tableFirst,
                    tableRows: this.tableRows
                });
                const fallbackStart = this.apiService.listSize > 0
                    ? Math.max(0, Math.floor((this.apiService.listSize - 1) / this.tableRows) * this.tableRows)
                    : 0;
                if (model.length === 0 && this.tableFirst > 0 && fallbackStart !== this.tableFirst) {
                    this.tableFirst = fallbackStart;
                    this.apiService._start = fallbackStart;
                    if (datatable) {
                        datatable.first = fallbackStart;
                    }
                    this.persistListState();
                    this.loaddata(datatable);
                    return;
                }

                for (let element of model) {
                    if (element != null) {
                        element[this.rawTableKeyField] = tableKeyFieldName
                            ? this.getElementPropertyValue(element as Record<string, unknown>, tableKeyFieldName)
                            : null;

                        for (const definition_1 of this.fieldDefinitionsList) {
                            if (!definition_1.name) {
                                continue;
                            }
                            definition_1.is_edit = true;
                            const existingPropertyName = this.getElementPropertyName(element as Record<string, unknown>, definition_1.name);
                            //cerco la field defintion
                            if (existingPropertyName) {
                                // Se è la mia devo scrivere il dato come observable
                                element[definition_1.name] = this.datoAsObservableOfValue(element, definition_1);
                            }
                        }
                    }
                }
                this.model = model;
                this.cdr.detectChanges();
            }
        );
    }

