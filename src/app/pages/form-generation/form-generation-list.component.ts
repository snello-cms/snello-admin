    public lazyLoad(
        event: any, datatable?: any) {

        this.debug('lazyLoad:event', {
            event,
            metadataReady: this.metadataReady,
            definitionsReady: this.definitionsReady,
            activeSearchValues: this.activeSearchValues
        });

        if (!this.metadataReady || !this.definitionsReady) {
            this.pendingLazyEvent = event;
            this.debug('lazyLoad:queued', {pendingLazyEvent: this.pendingLazyEvent});
            return;
        }

        this.tableFirst = event.first ?? 0;
        this.apiService._start = this.tableFirst;
        this.tableRows = event.rows ?? this.tableRows;
        this.apiService._limit = this.tableRows;
        this.initialLoadTriggered = true;
        this.persistListState();
        this.loaddata(datatable);
    }

    public getTableKey(fieldDefinition: any): string {
        const tableKeyFieldName = this.getTableKeyFieldName();
        const rawValue = fieldDefinition?.[this.rawTableKeyField]
            ?? (tableKeyFieldName
                ? this.getElementPropertyValue(fieldDefinition as Record<string, unknown>, tableKeyFieldName)
                : null);
        return this.resolveTableKeyValue(rawValue);
    }

    public reload(datatable: any) {
        this.syncActiveSearchValuesFromForm();
        this.debug('reload', {
            activeSearchValues: this.activeSearchValues
        });
        this.tableFirst = 0;
        this.apiService._start = 0;
        this.apiService._limit = this.tableRows;
        this.initialLoadTriggered = true;
        if (datatable) {
            datatable.first = 0;
        }
        this.loaddata(datatable);
    }

    public onSearchEnter(event: Event, datatable: any) {
        event.preventDefault();
        this.reload(datatable);
    }

    public refresh(datatable: any) {
        this.clearMsgs();
        this.loaddata(datatable);
    }

    public reset(datatable: any) {
        const obj: Record<string, unknown> = {};
        if (this.searchForm && this.searchForm.value) {
            for (const k in this.searchForm.value) {
                if (this.searchForm.value.hasOwnProperty(k)) {
                    obj[k] = null;
                }
            }
            for (const field of this.fieldDefinitionsSearch) {
                if (field.name && isPassivationSearchField(field)) {
                    obj[field.name] = true;
                    field.value = true;
                }
            }
            this.searchForm.searchForm.setValue(obj);
        }
        this.activeSearchValues = {...obj};
        this.debug('reset', {
            activeSearchValues: this.activeSearchValues
        });
        this.tableFirst = 0;
        this.apiService._start = 0;
        this.apiService._limit = this.tableRows;
        this.initialLoadTriggered = true;
        this.clearListStateCache();
        if (datatable) {
            datatable.first = 0;
        }
        this.lastAutoGeneratedRangeMax.clear();
        this.loaddata(datatable);
    }

